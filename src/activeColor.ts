function isLightTheme(): boolean {
  const kind = vscode.window.activeColorTheme.kind;
  return (
    kind === vscode.ColorThemeKind.Light ||
    kind === vscode.ColorThemeKind.HighContrastLight
  );
}

function nearestName(hex: string): ActiveColorName {
  const target = rgb(hex);
  let best: ActiveColorName = "green";
  let bestDistance = Number.POSITIVE_INFINITY;
  for (const name of Object.keys(PALETTE) as ActiveColorName[]) {
    const sample = rgb(PALETTE[name].dark);
    const distance =
      (target[0] - sample[0]) ** 2 +
      (target[1] - sample[1]) ** 2 +
      (target[2] - sample[2]) ** 2;
    if (distance < bestDistance) {
      best = name;
      bestDistance = distance;
    }
  }
  return best;
}

function rgb(hex: string): [number, number, number] {
  return [
    Number.parseInt(hex.slice(1, 3), 16),
    Number.parseInt(hex.slice(3, 5), 16),
    Number.parseInt(hex.slice(5, 7), 16),
  ];
}

export function activeHex(): string {
  const color = activeColorOf(cachedFoldersFile());
  if (color.kind === "hex") {
    return color.hex;
  }
  return PALETTE[color.name][isLightTheme() ? "light" : "dark"];
}

export function activeChartColor(): vscode.ThemeColor {
  const color = activeColorOf(cachedFoldersFile());
  const name = color.kind === "name" ? color.name : nearestName(color.hex);
  return new vscode.ThemeColor(CHARTS[name]);
}

export function coloredIconUri(iconId: string, hex: string): vscode.Uri {
  const paths = ICON_PATHS[iconId] ?? ICON_PATHS.server;
  const body = paths.map((d) => `<path fill="${hex}" d="${d}"/>`).join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">${body}</svg>`;
  return vscode.Uri.parse(`data:image/svg+xml,${encodeURIComponent(svg)}`);
}
